fn default_output_path() -> PathBuf {
    // CARGO_MANIFEST_DIR points at crates/codeless-rpc; the repo root
    // is two levels up. Keeping the path computed (not hardcoded as a
    // relative string) means `cargo run` from any directory still
    // writes to the correct file.
    let repo_root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crate manifest must be nested under the repo root");
    repo_root.join("ui/codeless-ui/src/lib/rpc/generated/wire.ts")
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let output = args
        .get(1)
        .map(PathBuf::from)
        .unwrap_or_else(default_output_path);

    let types = collect();
    let ts = Typescript::default().bigint(BigIntExportBehavior::Number);
    let body = ts.export(&types).expect("export typescript");

    // Strip the per-call specta header so the file begins with the
    // codegen banner above, then re-emit the (deterministic) body. The
    // snapshot tests still validate that specta produced the expected
    // text; this file is the seam where two crates' snapshots become
    // one UI import.
    let body = body
        .strip_prefix(
            "// This file has been generated by Specta. Do not edit this file manually.\n",
        )
        .unwrap_or(&body);

    if let Some(parent) = output.parent() {
        std::fs::create_dir_all(parent).expect("create output dir");
    }
    let mut out = String::with_capacity(HEADER.len() + body.len());
    out.push_str(HEADER);
    out.push_str(body);

    std::fs::write(&output, &out).expect("write wire.ts");
    eprintln!("wrote {} bytes to {}", out.len(), output.display());
}
