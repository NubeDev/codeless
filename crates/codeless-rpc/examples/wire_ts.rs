//! Emits the combined TypeScript wire contract that the UI compiles
//! against. The output is the concatenation of the two specta snapshots
//! (`codeless-types` core domain types and `codeless-rpc` method
//! args/results plus the subscribe filter) — both crates render their
//! own snapshot to avoid a `types -> rpc` dev-dependency cycle, and
//! this binary stitches them together at the seam where the UI consumes
//! a single module.
//!
//! Usage:
//!   cargo run -p codeless-rpc --example wire_ts -- <output-path>
//!
//! The output path defaults to
//! `ui/codeless-ui/src/lib/rpc/generated/wire.ts` resolved against the
//! inner-codeless repo root, which is what the UI build expects.
//!
//! This lives as an example (rather than a bin) because the
//! `specta-typescript` dependency only needs to exist at codegen time;
//! `[[example]]` targets resolve dev-dependencies, so `codeless-rpc`'s
//! normal build (and the mobile-reach graph it participates in) stays
//! free of the codegen-only crate.

